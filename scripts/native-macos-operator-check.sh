test -x "$app_dir/script/package_dmg.sh"
test -f ".codex/environments/environment.toml"

grep -q 'name: "MDxWorkbench"' "$app_dir/Package.swift"
grep -q 'sparkle-project/Sparkle.git", exact: "2.9.4"' "$app_dir/Package.swift"
grep -q 'product(name: "Sparkle"' "$app_dir/Package.swift"
grep -q 'Authorization.*Bearer' "$app_dir/Sources/MDxOperator/Services/MacUpdaterController.swift"
grep -q 'checkForUpdateInformation' "$app_dir/Sources/MDxOperator/Services/MacUpdaterController.swift"
