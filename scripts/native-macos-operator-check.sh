! grep -q -- '--entitlements' "$app_dir/script/notarize.sh"
! grep -q 'APPLE_DEVELOPER_ID_PROVISIONING_PROFILE_BASE64' ".github/workflows/macos-canary-release.yml"
grep -q 'apple_sign_in_transport -string "browser_oauth"' "$app_dir/script/notarize.sh"

(cd "$app_dir" && swift build --disable-sandbox)

# Mapper contract checks: pin JSON-to-model mapping against kernel projection
# fixtures so a wire-shape regression fails here, not as a blank surface.
(cd "$app_dir" && MDX_MAPPER_FIXTURES="$PWD/Tests/Fixtures" ./.build/debug/MDxWorkbench --mapper-checks)

# Xcode-backed XCTest proof. The parity suite defaults to an in-process HTTP
# fixture and only targets a live kernel when MDX_PARITY_BASE_URL is explicit.
(cd "$app_dir" && swift test --disable-sandbox)

echo "native_macos_operator_check: OK app=$app_dir xctest=deterministic"
