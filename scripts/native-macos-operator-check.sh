grep -q './apps/mdx-operator-macos/script/build_and_run.sh' ".codex/environments/environment.toml"
grep -q 'provider: .apple' "$app_dir/Sources/MDxOperator/Services/CloudAuthStore.swift"
grep -q 'signInWithOAuth' "$app_dir/Sources/MDxOperator/Services/CloudAuthStore.swift"
