grep -q 'http://127.0.0.1:18890' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/runtime-projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/repos/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/recipes.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/long-horizon-missions/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/fleet-plans/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/control-plane/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/build-requests/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/ship-decisions/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/source-host-readiness.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/pr-handoffs.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/browser-audits.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/machine-league/fleet-runs/arbitrations/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/learning/memory-activations/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/learning/adaptation-grants/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/memory/consolidation-ratifications/projection.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/forge/model-scorecard.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q '/learning/memory-supersedes.json' "$app_dir/Sources/MDxOperator/Services/MDxRouteClient.swift"
grep -q 'PRODUCT_NAME="MDxWorkbench"' "$app_dir/script/build_and_run.sh"
grep -q 'DISPLAY_NAME="MDx"' "$app_dir/script/build_and_run.sh"
grep -q 'BUNDLE_ID="com.mdx.app"' "$app_dir/script/build_and_run.sh"
grep -q 'MDX_API_URL' "$app_dir/script/build_and_run.sh"
grep -q -- '--env "MDX_API_URL=' "$app_dir/script/build_and_run.sh"
grep -q 'MDX_SHOT_TAB' "$app_dir/script/build_and_run.sh"
grep -q 'Start a build' "$app_dir/Sources/MDxOperator/Views/DetailView.swift"
grep -q 'GovernedActionKind' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q '/forge/build-requests.json' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q '/forge/pr-handoffs.json' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q 'script/package_release.sh' "$app_dir/Sources/MDxOperator/Views/DetailView.swift"
grep -q 'NavigationSplitView' "$app_dir/Sources/MDxOperator/Views/ContentView.swift"
grep -q 'inspector(isPresented:' "$app_dir/Sources/MDxOperator/Views/ContentView.swift"
grep -q 'enum AppRoute' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q 'case twin' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q 'case marketplace' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q 'case memory' "$app_dir/Sources/MDxOperator/Models/OperatorModels.swift"
grep -q 'TwinComposerCard' "$app_dir/Sources/MDxOperator/Views/DetailView.swift"
grep -q 'CommandPaletteView' "$app_dir/Sources/MDxOperator/Views/CommandPaletteView.swift"
grep -q 'NSViewRepresentable' "$app_dir/Sources/MDxOperator/Views/BrowserPreviewView.swift"
grep -q 'websiteDataStore = .nonPersistent' "$app_dir/Sources/MDxOperator/Views/BrowserPreviewView.swift"
grep -q 'compileContentRuleList' "$app_dir/Sources/MDxOperator/Views/BrowserPreviewView.swift"
grep -q 'startBrowserEvolution' "$app_dir/Sources/MDxOperator/Stores/OperatorStore.swift"
grep -q 'Shipping stays a human decision' "$app_dir/Sources/MDxOperator/Views/DetailView.swift"
