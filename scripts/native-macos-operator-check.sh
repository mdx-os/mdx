grep -q 'dmg_sha256' "$app_dir/script/notarize.sh"
grep -q 'application/x-apple-diskimage' ".github/workflows/macos-canary-release.yml"
grep -q 'SPARKLE_EDDSA_PRIVATE_KEY_BASE64' ".github/workflows/macos-canary-release.yml"
test -f "apps/mdx-host/src/routes/download/macos/appcast.xml/+server.js"
test -f "apps/mdx-host/src/routes/download/macos/update.zip/+server.js"
test -f "apps/mdx-host/src/routes/download/macos/installer.dmg/+server.js"
! grep -Eq '^[[:space:]]*codesign .*--deep' "$app_dir/script/stage_bundle.sh" "$app_dir/script/notarize.sh"
autoupdate_sign_line="$(grep -n 'SPARKLE_FRAMEWORK/Versions/Current/Autoupdate' "$app_dir/script/notarize.sh" | tail -1 | cut -d: -f1)"
app_sign_line="$(grep -n 'sign "\$MDX_SIGN_IDENTITY" "\$APP_BUNDLE"' "$app_dir/script/notarize.sh" | tail -1 | cut -d: -f1)"
[[ "$autoupdate_sign_line" -lt "$app_sign_line" ]]
